/** The user's saved text for a question. It belongs to the question, not to the card. */
export interface Note {
  questionId: string
  text: string
  updatedAt: string
}

/** Shape of the backend's error bodies (RFC 9457 ProblemDetails; `errors` is set for validation failures). */
interface ProblemDetails {
  title?: string
  detail?: string
  errors?: Record<string, string[]>
}

export class ApiError extends Error {
  status: number
  /** Field name to messages, present for 400 validation problems. */
  errors?: Record<string, string[]>

  constructor(status: number, message: string, errors?: Record<string, string[]>) {
    super(message)
    this.name = 'ApiError'
    this.status = status
    this.errors = errors
  }
}

async function toApiError(response: Response): Promise<ApiError> {
  let problem: ProblemDetails | undefined
  try {
    problem = (await response.json()) as ProblemDetails
  } catch {
    // Not JSON (for example an nginx error page); fall back to the status line.
  }
  const message = problem?.detail ?? problem?.title ?? `${response.status} ${response.statusText}`
  return new ApiError(response.status, message, problem?.errors)
}

async function request<T>(path: string, init?: RequestInit): Promise<T> {
  const response = await fetch(path, init)
  if (!response.ok) throw await toApiError(response)
  return response.status === 204 ? (undefined as T) : ((await response.json()) as T)
}

const get = <T>(path: string) => request<T>(path)

/** The browser's IANA time zone; the backend uses it to decide where "today" starts. */
export const browserTimeZone = () => Intl.DateTimeFormat().resolvedOptions().timeZone

function studyParams(topics: readonly Topic[], extra: Record<string, string | undefined> = {}) {
  const params = new URLSearchParams()
  for (const topic of topics) params.append('topic', topic)
  params.set('tz', browserTimeZone())
  for (const [key, value] of Object.entries(extra)) if (value !== undefined) params.set(key, value)
  return params
}

export const api = {
  getTopics: () => get<TopicSummary[]>('/api/topics'),
  getQuestions: ({ topic, limit, offset }: { topic?: Topic; limit?: number; offset?: number } = {}) => {
    const params = new URLSearchParams()
    if (topic) params.set('topic', topic)
    if (limit !== undefined) params.set('limit', String(limit))
    if (offset !== undefined) params.set('offset', String(offset))
    const query = params.toString()
    return get<Page<Question>>(query ? `/api/questions?${query}` : '/api/questions')
  },

  getStudySummary: () => get<StudySummary>(`/api/study/summary?${new URLSearchParams({ tz: browserTimeZone() })}`),
  getStudyQueue: (topics: readonly Topic[], limit?: number) =>
    get<StudyQueueItem[]>(`/api/study/queue?${studyParams(topics, { limit: limit?.toString() })}`),
  postReview: (review: ReviewRequest) =>
    request<ReviewResult>('/api/study/reviews', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(review),
    }),
  getAiStatus: () => get<AiStatus>(`/api/ai/status?${new URLSearchParams({ tz: browserTimeZone() })}`),
  checkAnswer: (questionId: string, answer: string) =>
    request<CheckAnswerResult>(`/api/ai/answers/check?${new URLSearchParams({ tz: browserTimeZone() })}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ questionId, answer }),
    }),
  /** The attempts for one question, newest first. */
  getAnswerAttempts: (questionId: string) =>
    get<Page<AnswerAttempt>>(`/api/ai/answers/attempts?${new URLSearchParams({ questionId })}`),

  /** One-shot: nothing is stored. Only partial or incorrect attempts can be explained. */
  explainMistakes: (attemptId: string) =>
    request<ExplainMistakesResult>(`/api/ai/answers/explain?${new URLSearchParams({ tz: browserTimeZone() })}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ attemptId }),
    }),

  /** The question's note, or null when it has none. */
  getNote: async (questionId: string): Promise<Note | null> => {
    try {
      return await get<Note>(`/api/questions/${questionId}/note`)
    } catch (e) {
      if (e instanceof ApiError && e.status === 404) return null
      throw e
    }
  },
  /** Saves the note, replacing any existing one. Ask the user first when one exists. */
  saveNote: (questionId: string, text: string) =>
    request<Note>(`/api/questions/${questionId}/note`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text }),
    }),

  /** Undo. A review that is already gone (404) counts as undone. */
  undoReview: async (reviewId: string) => {
    try {
      await request<void>(`/api/study/reviews/${reviewId}`, { method: 'DELETE' })
    } catch (e) {
      if (!(e instanceof ApiError && e.status === 404)) throw e
    }
  },
}
