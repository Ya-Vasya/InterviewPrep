/** The user's self-assessment of a card. Not the question's Difficulty. */
export type Rating = 'Again' | 'Hard' | 'Good' | 'Easy'

/** Interval in days each rating would produce; 0 means due again immediately. */
export interface RatingIntervals {
  again: number
  hard: number
  good: number
  easy: number
}

export interface TopicStudySummary {
  topic: Topic
  name: string
  dueCount: number
  newCount: number
  /** ISO timestamp of the earliest card that is not due yet, if any. */
  nextDueAt: string | null
}

export interface StudySummary {
  topics: TopicStudySummary[]
  newRemainingToday: number
  reviewsRemainingToday: number
}

export interface StudyQueueItem {
  questionId: string
  /** Null for a new card: it only exists once its first rating is recorded. */
  cardId: string | null
  topic: Topic
  difficulty: Difficulty
  text: string
  answer: string
  tags: string[]
  isNew: boolean
  intervals: RatingIntervals
}

export interface ReviewRequest {
  questionId: string
  rating: Rating
  /** Generated by the client when the card is shown; makes the request idempotent. */
  reviewId: string
  /** The AI check this rating follows, if the user typed an answer first. The server decides whether it counts as AI-assisted. */
  attemptId?: string
}

export interface ReviewResult {
  reviewId: string
  cardId: string
  dueAt: string
  intervalDays: number
  nextIntervals: RatingIntervals
}

